const mongoose = require("mongoose");

const Grade = require("../models/Grade.model");
const Student = require("../models/Student.model");
const Teacher = require("../models/Teacher.model");
const SchoolYear = require("../models/SchoolYear.model");
const GradeLevel = require("../models/GradeLevel.model");

/* =========================================================
   HELPERS
========================================================= */

function normalize(value) {
  return String(value ?? "").trim();
}

/**
 * Get the logged-in teacher.
 *
 * Supports the different session shapes currently used
 * throughout BLIMS.
 */
async function getTeacherBySession(req) {
  const sessionUserId =
    req.session?.user?.id ||
    req.session?.user?._id ||
    req.session?.userId;

  if (!sessionUserId) {
    return null;
  }

  return Teacher.findOne({
    userId: sessionUserId,
    isActive: true,
  }).lean();
}

/**
 * Get the active school year.
 */
async function getActiveSchoolYear() {
  return SchoolYear.findOne({
    isActive: true,
  }).lean();
}

/**
 * Get the teacher's assigned class and section.
 */
function getTeacherScope(teacher) {
  return {
    className: normalize(
      teacher?.handledClass ||
        teacher?.className ||
        teacher?.gradeLevel ||
        teacher?.grade ||
        teacher?.advisoryClass
    ),

    sectionName: normalize(
      teacher?.handledSection ||
        teacher?.sectionName ||
        teacher?.section ||
        teacher?.advisorySection
    ),
  };
}

/**
 * Get subjects assigned to a grade level.
 */
async function getSubjectsForGrade(className) {
  if (!className) {
    return [];
  }

  const gradeLevel = await GradeLevel.findOne({
    grade: className,
  }).lean();

  return Array.isArray(gradeLevel?.subjects)
    ? gradeLevel.subjects
    : [];
}

/**
 * Find a term from the active school year.
 */
function findSchoolYearTerm(schoolYear, termId) {
  if (!schoolYear || !Array.isArray(schoolYear.terms)) {
    return null;
  }

  return schoolYear.terms.find(
    (term) => String(term._id) === String(termId)
  );
}

/**
 * Normalize an assessment before saving.
 *
 * assessmentId is generated by the frontend and MUST be
 * preserved so the same assessment has the same identity
 * across every student.
 */
function normalizeAssessment(assessment) {
  if (!assessment || typeof assessment !== "object") {
    return null;
  }

  const assessmentId = normalize(
    assessment.assessmentId || assessment.id
  );

  const activity = normalize(
    assessment.activity || assessment.name
  );

  const total = Number(assessment.total);

  let score = null;

  if (
    assessment.score !== null &&
    assessment.score !== undefined &&
    assessment.score !== ""
  ) {
    score = Number(assessment.score);
  }

  if (!assessmentId) {
    throw new Error("Assessment ID is required.");
  }

  if (!activity) {
    throw new Error("Assessment activity is required.");
  }

  if (!Number.isFinite(total) || total < 1) {
    throw new Error("Assessment total must be at least 1.");
  }

  if (
    score !== null &&
    (!Number.isFinite(score) || score < 0 || score > total)
  ) {
    throw new Error(
      `Assessment score must be between 0 and ${total}.`
    );
  }

  return {
    assessmentId,
    activity,
    score,
    total,
  };
}

/**
 * Normalize the term assessment/exam.
 */
function normalizeTermAssessment(assessment) {
  if (!assessment || typeof assessment !== "object") {
    return null;
  }

  const assessmentId = normalize(
    assessment.assessmentId || assessment.id
  );

  const activity = normalize(
    assessment.activity || assessment.name
  );

  let total = null;
  let score = null;

  if (
    assessment.total !== null &&
    assessment.total !== undefined &&
    assessment.total !== ""
  ) {
    total = Number(assessment.total);
  }

  if (
    assessment.score !== null &&
    assessment.score !== undefined &&
    assessment.score !== ""
  ) {
    score = Number(assessment.score);
  }

  if (!assessmentId) {
    throw new Error("Term assessment ID is required.");
  }

  if (!activity) {
    throw new Error("Term assessment name is required.");
  }

  if (
    total !== null &&
    (!Number.isFinite(total) || total < 1)
  ) {
    throw new Error(
      "Term assessment total must be at least 1."
    );
  }

  if (
    score !== null &&
    total !== null &&
    (!Number.isFinite(score) || score < 0 || score > total)
  ) {
    throw new Error(
      `Term assessment score must be between 0 and ${total}.`
    );
  }

  return {
    assessmentId,
    activity,
    score,
    total,
  };
}

/* =========================================================
   GET GRADE ENCODING DATA
========================================================= */

async function getGradeEncodingData(req, res) {
  try {
    const teacher = await getTeacherBySession(req);

    if (!teacher) {
      return res.status(401).json({
        message: "Teacher session not found.",
      });
    }

    const teacherScope = getTeacherScope(teacher);

    if (
      !teacherScope.className ||
      !teacherScope.sectionName
    ) {
      return res.status(400).json({
        message:
          "Teacher class and section are not properly configured.",
      });
    }

    const schoolYear = await getActiveSchoolYear();

    if (!schoolYear) {
      return res.status(404).json({
        message: "No active school year found.",
      });
    }

    const students = await Student.find({
      isActive: true,
      gradeLevel: teacherScope.className,
      sectionName: teacherScope.sectionName,
    })
      .select(
        "_id studentId firstName middleName lastName suffix gradeLevel sectionName"
      )
      .lean();

    students.sort((a, b) => {
      const lastA = normalize(a.lastName).toLowerCase();
      const lastB = normalize(b.lastName).toLowerCase();

      if (lastA !== lastB) {
        return lastA.localeCompare(lastB);
      }

      const firstA = normalize(a.firstName).toLowerCase();
      const firstB = normalize(b.firstName).toLowerCase();

      return firstA.localeCompare(firstB);
    });

    const subjects = await getSubjectsForGrade(
      teacherScope.className
    );

    const terms = Array.isArray(schoolYear.terms)
      ? [...schoolYear.terms]
          .sort((a, b) => a.order - b.order)
          .map((term) => ({
            id: String(term._id),
            order: term.order,
            name: normalize(term.name),
            start: term.start || null,
            end: term.end || null,
            locked: Boolean(term.locked),
          }))
      : [];

    return res.json({
      teacherScope,

      schoolYear: {
        id: String(schoolYear._id),
        name: normalize(schoolYear.name),
        terms,
      },

      students,

      subjects,
    });
  } catch (error) {
    console.error(
      "getGradeEncodingData error:",
      error
    );

    return res.status(500).json({
      message: "Failed to load grade encoding data.",
    });
  }
}

/* =========================================================
   SAVE GRADE
========================================================= */

async function saveGrade(req, res) {
  try {
    const teacher = await getTeacherBySession(req);

    if (!teacher) {
      return res.status(401).json({
        message: "Teacher session not found.",
      });
    }

    const teacherScope = getTeacherScope(teacher);

    const schoolYear = await getActiveSchoolYear();

    if (!schoolYear) {
      return res.status(404).json({
        message: "No active school year found.",
      });
    }

    const studentId = normalize(req.body.studentId);
    const subject = normalize(req.body.subject);
    const termId = normalize(req.body.termId);

    if (!studentId) {
      return res.status(400).json({
        message: "Student ID is required.",
      });
    }

    if (!subject) {
      return res.status(400).json({
        message: "Subject is required.",
      });
    }

    if (!termId) {
      return res.status(400).json({
        message: "Term ID is required.",
      });
    }

    if (!mongoose.Types.ObjectId.isValid(termId)) {
      return res.status(400).json({
        message: "Invalid term ID.",
      });
    }

    /* -------------------------------------------------------
       TERM VALIDATION
    ------------------------------------------------------- */

    const term = findSchoolYearTerm(
      schoolYear,
      termId
    );

    if (!term) {
      return res.status(404).json({
        message: "Term not found in the active school year.",
      });
    }

    /*
     * IMPORTANT:
     * Locking is enforced on the backend.
     *
     * Do NOT remove this.
     */
    if (term.locked) {
      return res.status(403).json({
        message:
          "This term is locked and can no longer be edited.",
      });
    }

    /* -------------------------------------------------------
       STUDENT VALIDATION
    ------------------------------------------------------- */

    const student = await Student.findOne({
      studentId,
      isActive: true,
      gradeLevel: teacherScope.className,
      sectionName: teacherScope.sectionName,
    }).lean();

    if (!student) {
      return res.status(403).json({
        message:
          "You are not allowed to encode grades for this student.",
      });
    }

    /* -------------------------------------------------------
       SUBJECT VALIDATION
    ------------------------------------------------------- */

    const subjects =
      await getSubjectsForGrade(
        teacherScope.className
      );

    const validSubject = subjects.some(
      (item) => {
        const subjectName =
          typeof item === "string"
            ? item
            : item?.name ||
              item?.subject ||
              item?.subjectName;

        return (
          normalize(subjectName).toLowerCase() ===
          subject.toLowerCase()
        );
      }
    );

    if (!validSubject) {
      return res.status(400).json({
        message:
          "This subject is not assigned to the teacher's grade level.",
      });
    }

    /* -------------------------------------------------------
       ASSESSMENTS
    ------------------------------------------------------- */

    let writtenWorks = [];

    let performanceTasks = [];

    try {
      if (Array.isArray(req.body.writtenWorks)) {
        writtenWorks = req.body.writtenWorks.map(
          normalizeAssessment
        );
      }

      if (Array.isArray(req.body.performanceTasks)) {
        performanceTasks =
          req.body.performanceTasks.map(
            normalizeAssessment
          );
      }
    } catch (assessmentError) {
      return res.status(400).json({
        message: assessmentError.message,
      });
    }

    /* -------------------------------------------------------
       TERM ASSESSMENT
    ------------------------------------------------------- */

    let termAssessment = null;

    if (
      req.body.termAssessment &&
      typeof req.body.termAssessment === "object"
    ) {
      try {
        termAssessment =
          normalizeTermAssessment(
            req.body.termAssessment
          );
      } catch (assessmentError) {
        return res.status(400).json({
          message: assessmentError.message,
        });
      }
    }

    /* -------------------------------------------------------
       GRADES
    ------------------------------------------------------- */

    let initialGrade = null;

    if (
      req.body.initialGrade !== null &&
      req.body.initialGrade !== undefined &&
      req.body.initialGrade !== ""
    ) {
      const value = Number(req.body.initialGrade);

      if (
        Number.isFinite(value) &&
        value >= 0 &&
        value <= 100
      ) {
        initialGrade = value;
      }
    }

    let termGrade = null;

    if (
      req.body.termGrade !== null &&
      req.body.termGrade !== undefined &&
      req.body.termGrade !== ""
    ) {
      const value = Number(req.body.termGrade);

      if (
        Number.isFinite(value) &&
        value >= 0 &&
        value <= 100
      ) {
        termGrade = value;
      }
    }

    /* -------------------------------------------------------
       SAVE
    ------------------------------------------------------- */

    const savedGrade =
      await Grade.findOneAndUpdate(
        {
          studentId,
          subject,
          termId,
          schoolYearId: schoolYear._id,
        },

        {
          $set: {
            studentId,

            gradeLevel:
              teacherScope.className,

            sectionName:
              teacherScope.sectionName,

            subject,

            schoolYearId:
              schoolYear._id,

            schoolYearName:
              normalize(schoolYear.name),

            termId,

            writtenWorks,

            performanceTasks,

            termAssessment,

            initialGrade,

            termGrade,

            teacherId: teacher._id,
          },
        },

        {
          upsert: true,
          returnDocument: "after",
          setDefaultsOnInsert: true,
          runValidators: true,
        }
      ).lean();

    return res.status(200).json({
      message: "Grade saved successfully.",
      grade: savedGrade,
    });
  } catch (error) {
    console.error(
      "saveGrade error:",
      error
    );

    return res.status(500).json({
      message: "Failed to save grade.",
      error: error.message,
    });
  }
}

/* =========================================================
   GET SAVED GRADES
========================================================= */

async function getSavedGrades(req, res) {
  try {
    const teacher = await getTeacherBySession(req);

    if (!teacher) {
      return res.status(401).json({
        message: "Teacher session not found.",
      });
    }

    const teacherScope = getTeacherScope(teacher);

    const schoolYear = await getActiveSchoolYear();

    if (!schoolYear) {
      return res.status(404).json({
        message: "No active school year found.",
      });
    }

    const grades = await Grade.find({
      teacherId: teacher._id,

      gradeLevel:
        teacherScope.className,

      sectionName:
        teacherScope.sectionName,

      schoolYearId:
        schoolYear._id,
    })
      .sort({
        subject: 1,
        studentId: 1,
      })
      .lean();

    /*
     * Sort terms according to the actual school-year
     * term order rather than assuming Q1/Q2/Q3/Q4.
     */
    const termOrderMap = new Map(
      (schoolYear.terms || []).map(
        (term) => [
          String(term._id),
          term.order,
        ]
      )
    );

    grades.sort((a, b) => {
      const subjectCompare =
        normalize(a.subject).localeCompare(
          normalize(b.subject)
        );

      if (subjectCompare !== 0) {
        return subjectCompare;
      }

      const termA =
        termOrderMap.get(
          String(a.termId)
        ) ?? 999;

      const termB =
        termOrderMap.get(
          String(b.termId)
        ) ?? 999;

      if (termA !== termB) {
        return termA - termB;
      }

      return normalize(
        a.studentId
      ).localeCompare(
        normalize(b.studentId)
      );
    });

    return res.json({
      schoolYear: {
        id: String(schoolYear._id),
        name: normalize(schoolYear.name),
        terms: (schoolYear.terms || [])
          .sort((a, b) => a.order - b.order)
          .map((term) => ({
            id: String(term._id),
            order: term.order,
            name: normalize(term.name),
            start: term.start || null,
            end: term.end || null,
            locked: Boolean(term.locked),
          })),
      },

      grades,
    });
  } catch (error) {
    console.error(
      "getSavedGrades error:",
      error
    );

    return res.status(500).json({
      message: "Failed to load saved grades.",
    });
  }
}

